// Product display layer, 25 MHz pixel domain, active-high async reset.
// Three registered stages (S1 image adjust + ROM addresses, S2 fade/ECO + glyph fetch,
// S3 overlay compose); out_de/out_vs follow the same three-stage delay.
// x,y are output-display coordinates (upper-left origin) aligned with de and pixel.
// Every user parameter is captured at frame_start (vertical blank), never mid-frame.
//
// Layers, lowest first: image (or boot/fault background) -> debug status line and
// waveform (debug only) -> caption band with tag -> emergency border -> boot/fault
// centre message -> settings menu -> underflow marker (debug only).
// ROMs (generated by scripts/prepare_assets.py, loaded with eram_init):
//   osd_glyphs.hex   256 cells x 16 rows x 16 bits (CJK or two ASCII characters per cell)
//   osd_messages.hex 8 rows x 64 cells: 0-2 captions per mode (3 spare), 4 fault caption,
//                    5 tags (2 cells each), 6 fault centre text, 7 loading centre text
//   osd_menu.hex     11 rows x 4 value variants x 32 cells (title, 8 items, key hint, save note)
//   ascii.hex        128 x 16 rows x 8 bits (debug status line)
module ed_video(
 input clk,rst,frame_start,input [9:0] x,y,input de,vs,
 input [23:0] pixel,input ready,fault,underflow,
 // Cross-fade: pixel_old (previous image, same alignment as pixel), weight mix/16 for pixel.
 input [23:0] pixel_old,input blend,input [4:0] mix,
 // mode: 0 normal, 1 notice, 2 emergency. index: SDRAM bank 0..5 (debug IMG:1..6).
 // osd: overlay transparency 0 opaque, 1 translucent, 2 clear (caption band and menu).
