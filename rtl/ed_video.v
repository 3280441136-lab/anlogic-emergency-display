 input [5:0] spec,           // spectrum bar height of bin spec_index, one clock after spec_rd
 input [5:0] spec_peak_bin,spec_peak_h,   // tallest bin and its height (quasi-static)
 // Diagnostics (pixel domain): read-check counters, refresh pulses/s,
 // SD data-CRC mismatch count (quasi-static storage value, used only while ready).
 input [7:0] diag_rd,diag_ld,input [15:0] diag_ref,input [7:0] diag_crc,
 // Settings flash (ed_settings_store status): F:D none, F:S stored, F:X absent, F:E error, F:W busy.
