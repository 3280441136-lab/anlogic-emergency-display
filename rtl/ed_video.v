 reg [3:0] gy1,gbit1,gbit2;reg [3:0] mrow1,mrow2;
 reg signed [7:0] wave1,wave_last;reg [5:0] spec1;
 wire [23:0] faded,faded_eco;reg [23:0] composed;   // defined below (S2 / S3 combinational)
 always @(posedge clk) begin
  // ROM reads (no reset: block RAM). Stage-0 address -> S1 data.
  msg_char<=messages[msg_addr];
  menu_char<=menu_text[{menu_row,variant,mx[8:4]}];
  if(de && debug_q && text_fetch) ascii_row1<=ascii[{text_char[6:0],text_row}];else ascii_row1<=0;
  // S1 -> S2: one glyph fetch per pixel from whichever text source owns the pixel.
  glyph_row<=glyphs[{menutext1?menu_char:msg_char,gy1}];
  ascii_row2<=ascii_row1;
 end
 always @(posedge clk or posedge rst) begin
  if(rst) begin
   b_q<=2;c_q<=2;v_q<=2;sel_q<=0;fx_q<=0;osd_q<=1;mode_q<=0;index_q<=0;eco_q<=0;auto_q<=1;debug_q<=1;menu_q<=0;
   sec_div<=0;s0<=0;s1<=0;m0<=0;m1<=0;h0<=0;h1<=0;
   scroll<=0;eco_frame<=0;frame_count<=0;rd_q<=0;ld_q<=0;crc_q<=0;ref_q<=0;spec_on<=0;
   x1<=0;x2<=0;y1<=0;y2<=0;d1<=0;d2<=0;v1<=1;v2<=1;rgb1<=0;rgb2<=0;out_de<=0;out_vs<=1;rgb<=0;
   menu1<=0;menu2<=0;menutext1<=0;menutext2<=0;tag1<=0;tag2<=0;cap1<=0;cap2<=0;center1<=0;center2<=0;
   gy1<=0;gbit1<=0;gbit2<=0;mrow1<=0;mrow2<=0;wave1<=0;wave_last<=0;
  end else begin
   if(frame_start) begin
    b_q<=brightness;c_q<=contrast;v_q<=volume;fx_q<=effect;osd_q<=osd;eco_q<=eco;auto_q<=auto_en;debug_q<=debug;
    menu_q<=menu_open;sel_q<=menu_sel;mode_q<=mode;index_q<=index;
    rd_q<=diag_rd;ld_q<=diag_ld;ref_q<=diag_ref;crc_q<=ready?diag_crc:8'd0;
    hz_q<=hz_txt(spec_peak_bin);spct_q<=pct_txt(spec_peak_h);wpct_q<=pct_txt(peak[7:2]);spec_on<=spec_peak_h!=0;
    frame_count<=frame_count+1'b1;eco_frame<=eco_frame+1'b1;
    if(!eco || eco_frame==0) scroll<=scroll+1'b1;
   end
   if(sec_div==25'd24999999) begin   // uptime, BCD ripple once per second
    sec_div<=0;
    if(s0!=9) s0<=s0+1'b1;else begin s0<=0;
     if(s1!=5) s1<=s1+1'b1;else begin s1<=0;
      if(m0!=9) m0<=m0+1'b1;else begin m0<=0;
       if(m1!=5) m1<=m1+1'b1;else begin m1<=0;
        if(h0!=9) h0<=h0+1'b1;else begin h0<=0;h1<=(h1==9)?4'd0:h1+1'b1;end
       end end end end
   end else sec_div<=sec_div+1'b1;
   // ---- S1 ----
   x1<=x;y1<=y;d1<=de;v1<=vs;
   menu1<=in_menu;menutext1<=in_menu&&menu_text_line;mrow1<=menu_row;
   tag1<=in_tag_text;cap1<=in_cap_text;center1<=in_center_text;
   gy1<=in_menu?my[3:0]-4'd8:y[3:0]-4'd8;   // all text lines start at y = 8 mod 16
   gbit1<=in_menu?mx[3:0]:in_center_text?center_x[3:0]:in_tag_text?tag_x[3:0]:cap_sx[3:0];
   if(de) begin
    if(ready&&!(wipe&&x>={reveal,4'b0})) rgb1<={adjusted(src[23:16],b_q,c_q),adjusted(src[15:8],b_q,c_q),adjusted(src[7:0],b_q,c_q)};
    else rgb1<=fault?24'h2a1218:24'h101c2e;
   end
   // ---- S2 ----
   x2<=x1;y2<=y1;d2<=d1;v2<=v1;
   menu2<=menu1;menutext2<=menutext1;mrow2<=mrow1;tag2<=tag1;cap2<=cap1;center2<=center1;gbit2<=gbit1;
   wave1<=wave;if(x2[0]) wave_last<=wave1;spec1<=spec;
   rgb2<=eco_q ? faded_eco : faded;
   // ---- S3 ----
   out_de<=d2;out_vs<=v2;
   rgb<=d2 ? composed : 24'd0;
  end
 end
 // ---------------- S2 combinational: fade and ECO dimming ----------------
 // Fade v*gain/16 without a multiplier: gain is 0..16 (5 bits), so the product is the sum
 // of v shifted by each set gain bit (adders only; no DSP in the pixel path).
 wire [12:0] fade_r=times_gain(rgb1[23:16],gain), fade_g=times_gain(rgb1[15:8],gain), fade_b=times_gain(rgb1[7:0],gain);
 assign faded={fade_r[11:4],fade_g[11:4],fade_b[11:4]};
 assign faded_eco={faded[23:16]-faded[23:18],faded[15:8]-faded[15:10],faded[7:0]-faded[7:2]};
 // ---------------- S3 combinational: overlay compose (uses S2 values) ----------------
 function [23:0] quarter;input [23:0] c;begin quarter={2'b0,c[23:18],2'b0,c[15:10],2'b0,c[7:2]};end endfunction
 function [23:0] eighth;input [23:0] c;begin eighth={3'b0,c[23:19],3'b0,c[15:11],3'b0,c[7:3]};end endfunction
 function [23:0] half;input [23:0] c;begin half={1'b0,c[23:17],1'b0,c[15:9],1'b0,c[7:1]};end endfunction
 // Overlay panel: image share 0, 1/4 or 1/2 (osd 0 opaque / 1 translucent / 2 clear), the
 // tint takes the rest. Per-channel shifts and adds only; each channel sum stays <= 255.
 function [23:0] panel;input [23:0] img,tint;input [1:0] level;begin case(level)
  2'd0:panel=tint;
  2'd1:panel=quarter(img)+half(tint)+quarter(tint);
  default:panel=half(img)+half(tint);
 endcase end endfunction
 wire glyph_ink=glyph_row[4'd15-gbit2];
 // One-pixel drop shadow to the right of each stroke (left neighbour in the same glyph row)
 // keeps white text readable on translucent panels.
 wire glyph_shadow=gbit2!=0 && glyph_row[4'd15-gbit2+4'd1] && !glyph_ink;
 wire ascii_ink=ascii_row2[3'd7-x2[2:0]];
 wire [23:0] accent=(mode_q>=2)?24'hff4a4a:(mode_q==1)?24'hffa63d:24'hffc93c;
 wire [23:0] band=fault?24'h6a1a22:(mode_q>=2)?24'h8a1414:(mode_q==1)?24'h6a3a08:24'h121e33;
 wire flash=frame_count[5];
 wire emergency=ready&&mode_q>=2;
 wire notice=ready&&mode_q==1&&!fault;
 wire [9:0] wy_cur=WAVE_MID-{{4{wave1[7]}},wave1[7:2]};
 wire [9:0] wy_prev=WAVE_MID-{{4{wave_last[7]}},wave_last[7:2]};
 wire [9:0] wy_lo=(wy_cur<wy_prev)?wy_cur:wy_prev, wy_hi=(wy_cur<wy_prev)?wy_prev:wy_cur;
 wire [9:0] mx2=x2-MENU_X0, my2=y2-MENU_Y0;
 wire [9:0] bar_x=x2-BAR_X0;
 wire [9:0] spec_x2=x2-SPEC_X0;
 reg [2:0] bar_value;
 always @* case(mrow2) 4'd1:bar_value=b_q;4'd2:bar_value=c_q;default:bar_value=v_q; endcase
 wire bar_row=mrow2>=1 && mrow2<=3;
 wire in_bar=bar_row && x2>=BAR_X0 && x2<BAR_X0+128 && bar_x[4:0]<28 && my2[4:0]>=11 && my2[4:0]<21;
 wire bar_filled=bar_x[6:5]<bar_value;
 wire selected=mrow2==sel_q+1'b1;
 always @* begin
  composed=rgb2;
  if(debug_q) begin
   if(y2<24) composed=quarter(rgb2);
   if(y2>=4 && y2<20 && ascii_ink) composed=accent;
   if(ready && x2>=AUD_X0 && x2<AUD_X1 && y2>=AUD_Y0 && y2<AUD_Y1) composed=quarter(rgb2)+24'h0a1420;
   if(ready && x2>=WAVE_X0 && x2<WAVE_X1 && y2>=WAVE_Y0 && y2<WAVE_Y1) begin
    composed=eighth(rgb2)+24'h0c1a2a;
    if(y2==WAVE_MID-16 || y2==WAVE_MID+16 || x2==WAVE_X0+128) composed=24'h22384c;   // +-0.5 FS, mid time
    if(y2==WAVE_MID || y2==WAVE_Y0 || y2==WAVE_Y1-1) composed=24'h31536c;
    if(y2>=wy_lo && y2<=wy_hi+1) composed=accent;
   end
   if(ready && x2>=SPEC_X0 && x2<SPEC_X1 && y2>=WAVE_Y0 && y2<WAVE_Y1) begin
    composed=eighth(rgb2)+24'h0c1a2a;
    if(spec_x2==43 || spec_x2==85 || spec_x2==128 || spec_x2==171 || spec_x2==213 ||   // 500 Hz steps
       y2==WAVE_Y1-17 || y2==WAVE_Y1-33 || y2==WAVE_Y1-49) composed=24'h22384c;      // 25/50/75 %
    if(y2==WAVE_Y0 || y2==WAVE_Y1-1 || spec_x2==0) composed=24'h31536c;
    if(spec_x2[1:0]!=2'd3 && (WAVE_Y1-1-y2)<{4'd0,spec1}) composed=((WAVE_Y1-1-y2)+1=={4'd0,spec1})?24'hffffff:24'h4ad0ff;
   end
   if(ready && x2>=PEAK_X0 && x2<PEAK_X1 && y2>=WAVE_Y0 && y2<WAVE_Y1)
    composed=((WAVE_Y1-1-y2)<{4'd0,peak[7:2]})?accent:(eighth(rgb2)+24'h0c1a2a);
   // panel text: titles in the accent colour, readings white, axis labels grey
   if(ready && y2>=TITLE_Y && y2<TITLE_Y+16 && ascii_ink)
    composed=((x2>=184 && x2<216) || (x2>=456 && x2<544))?24'hffffff:accent;
   if(ready && ((y2>=TICK_Y && y2<TICK_Y+16) || (x2<WAVE_X0 && y2>=WAVE_Y0 && y2<WAVE_Y1)) && ascii_ink) composed=24'h9fb4c8;
  end
  if(y2>=CAP_Y0) begin
   composed=panel(rgb2,band,osd_q);
   if(x2>=TAG_X0 && x2<TAG_X1 && y2>=CAP_Y0+4 && y2<CAP_Y0+28) composed=accent;
   if(tag2 && glyph_ink) composed=(mode_q==0&&!fault)?24'h16233a:24'hffffff;
   if(cap2 && glyph_shadow) composed=24'h000000;
   if(cap2 && glyph_ink) composed=24'hffffff;
  end
  // Notice: steady thin orange frame (shops open); emergency: thick red frame flashing.
  if(notice && (x2<4 || x2>=636 || y2<4 || (y2>=CAP_Y0-4 && y2<CAP_Y0))) composed=24'hffa63d;
  if(emergency && flash && (x2<6 || x2>=634 || y2<6 || (y2>=CAP_Y0-6 && y2<CAP_Y0))) composed=24'hff2a2a;
  if(center2 && glyph_shadow) composed=24'h000000;
  if(center2 && glyph_ink) composed=fault?24'hff8080:24'hffc93c;
  if(menu2) begin
   composed=panel(rgb2,24'h142034,osd_q);
   if(mrow2==0) composed=24'hffc93c;
   else if(selected && mrow2<=8 && mx2>=4 && mx2<316 && my2[4:0]>=2 && my2[4:0]<30) composed=24'hffe08a;
   if(mx2==0 || mx2==319 || my2==0 || my2==MENU_Y1-MENU_Y0-1) composed=24'hffc93c;
   if(in_bar) composed=bar_filled?((selected)?24'h16233a:24'hffc93c):24'h4a5a70;
   if(menutext2 && glyph_shadow && mrow2!=0 && !selected && osd_q!=0) composed=24'h000000;
   if(menutext2 && glyph_ink) composed=(mrow2==0||selected)?24'h16233a:(mrow2==9)?24'h9aa8bb:(mrow2==10)?24'hffc93c:24'hffffff;
  end
  if(debug_q && (fault||underflow) && x2>=616 && x2<636 && y2>=4 && y2<20) composed=24'hff3030;
 end
